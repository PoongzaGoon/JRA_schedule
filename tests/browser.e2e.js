import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/server.js';
import { passwordHash } from '../src/auth.js';
import { createClient } from '@libsql/client';
import { openRemoteStore } from '../src/remote-store.js';
const dir = await mkdtemp(join(tmpdir(), 'jra-browser-'));
const origin = 'http://127.0.0.1:4217';
const remote = process.argv.includes('--libsql');
const store = remote ? openRemoteStore({}, createClient({ url: 'file:' + join(dir, 'remote.sqlite') })) : undefined;
const app = createApp({ APP_ORIGIN: origin, DATABASE_PATH: join(dir, 'test.sqlite'), ADMIN_PASSWORD_HASH: await passwordHash('browser-test-only-password-123') }, { store });
await new Promise(resolve => app.server.listen(4217, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined, args: ['--no-sandbox'] });
const errors = [];
const output = process.env.REVIEW_OUTPUT_DIR || 'work/browser';
await mkdir(output, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, locale: 'ko-KR' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('button', { name: '가상 예시 살펴보기' }).click();
  await page.getByRole('heading', { name: '이번 주 출주 노트' }).waitFor();
  assert.equal(await page.locator('tbody tr').count(), 7);
  await page.screenshot({ path: join(output, 'public-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '콘트레일' }).click();
  assert.equal(await page.locator('tbody tr').count(), 5);
  await page.getByLabel('일본어 원문 함께 보기').check();
  assert(await page.locator('.ja').count() > 0);
  await page.getByLabel('부가 열 보기').check();
  await page.getByRole('columnheader', { name: '인기', exact: true }).first().waitFor();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(origin);
  await mobile.getByRole('button', { name: '가상 예시 살펴보기' }).click();
  await mobile.getByRole('heading', { name: '이번 주 출주 노트' }).waitFor();
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile page must not overflow outside table scroll areas');
  await mobile.screenshot({ path: join(output, 'public-mobile.png'), fullPage: true });
  await page.goto(origin + '/admin');
  await page.getByLabel('관리자 비밀번호', { exact: true }).fill('browser-test-only-password-123');
  await page.getByRole('button', { name: '관리자 작업실 열기' }).click();
  await page.getByRole('heading', { name: '관리자 작업실', exact: true }).waitFor();
  await page.getByLabel('출주표 JSON').fill('{"invalid":');
  await page.getByRole('button', { name: '검증하고 미리보기' }).click();
  await page.getByText('수정 필요', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('출주표 JSON').inputValue(), '{"invalid":');
  assert.equal((await (await fetch(origin + '/api/public')).json()).publication, null);
  await page.getByRole('button', { name: '가상 예시 불러오기' }).click();
  await page.waitForFunction(() => document.querySelector('#json-editor')?.value.includes('\"schemaVersion\"'));
  const imported = await page.getByLabel('출주표 JSON').inputValue();
  await page.locator('#json-file').setInputFiles({ name: 'schedule.json', mimeType: 'application/json', buffer: Buffer.from(imported) });
  assert.equal(await page.getByLabel('출주표 JSON').inputValue(), imported);
  await page.getByRole('button', { name: '검증하고 미리보기' }).click();
  await page.getByText('형식 검증 통과', { exact: true }).waitFor();
  await page.locator('#preview').waitFor();
  const publish = page.getByRole('button', { name: '검토한 일정 게시', exact: true });
  assert(await publish.isDisabled());
  const imageRequests = [];
  const track = req => imageRequests.push(req.method());
  page.on('request', track);
  await page.locator('#capture-file').setInputFiles({ name: 'test.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j4ZkAAAAASUVORK5CYII=', 'base64') });
  await page.getByAltText('관리자가 대조용으로 선택한 원본 캡처').waitFor();
  assert(!imageRequests.includes('POST'), 'capture comparison must not upload images');
  page.off('request', track);
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(output, 'admin-desktop.png'), fullPage: true });
  await page.locator('#confirm-review').check();
  await publish.click();
  await page.getByText(/게시본 #1이 저장되어/).waitFor();
  assert.equal((await (await fetch(origin + '/api/public')).json()).publication.id, 1);
  // A second publication, followed by a review-based restore, keeps all revisions.
  const data = JSON.parse(await page.getByLabel('출주표 JSON').inputValue());
  data.notes = '브라우저 통합 검증 두 번째 게시본';
  data.stallions[0].raceDays[0].entries[0].horse.ko = '<img src=x onerror=alert(1)>';
  await page.getByLabel('출주표 JSON').fill(JSON.stringify(data));
  await page.getByRole('button', { name: '검증하고 미리보기' }).click();
  await page.getByText('형식 검증 통과', { exact: true }).waitFor();
  await page.locator('#confirm-review').check();
  await page.getByRole('button', { name: '검토한 일정 게시', exact: true }).click();
  await page.getByText(/게시본 #2이 저장되어/).waitFor();
  await mobile.reload();
  await mobile.getByText('<img src=x onerror=alert(1)>', { exact: true }).waitFor();
  assert.equal(await mobile.locator('img[src=x]').count(), 0, 'JSON text must never execute as HTML');
  await page.locator('[data-revision="1"]').click();
  await page.getByRole('button', { name: '#1 게시본으로 복원' }).waitFor();
  await page.locator('#confirm-review').check();
  await page.getByRole('button', { name: '#1 게시본으로 복원' }).click();
  await page.getByText(/게시본 #3이 복원되어/).waitFor();
  await page.getByRole('button', { name: '로그아웃', exact: true }).click();
  await page.getByRole('heading', { name: '관리자 로그인', exact: true }).waitFor();
  assert.equal(await page.getByLabel('관리자 비밀번호', { exact: true }).inputValue(), '');
  assert.deepEqual(errors, []);
  console.log((remote ? 'libSQL ' : 'SQLite ') + 'Browser QA passed: desktop/mobile, filtering, originals/extras, invalid input preservation, local capture preview, publish, restore, logout.');
} finally { await browser.close(); await app.close(); await rm(dir, { recursive: true, force: true }); }
